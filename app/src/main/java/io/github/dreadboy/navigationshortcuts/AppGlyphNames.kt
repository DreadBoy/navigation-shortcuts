package io.github.dreadboy.navigationshortcuts

/**
 * Readable app names for Niagara's per-app glyphs (`ic_ip_app_<package with _ for .>`, 549 in 1.16.33, PLAN 5b.4):
 * the picker label, accessibility label and search text ("Spotify" for `app_com_spotify_music`). Glyphs added by a
 * Niagara update that aren't listed get a name guessed from their package ([guess]).
 */
object AppGlyphNames {
    const val PREFIX = "app_"

    /** The app name for glyph [glyphName] (`app_com_spotify_music` → "Spotify"). */
    fun name(glyphName: String): String {
        val pkg = glyphName.removePrefix(PREFIX)
        return names[pkg] ?: guess(pkg)
    }

    /** Whether [glyphName] has a curated name (all 549 app glyphs of Niagara 1.16.33 do). */
    fun isListed(glyphName: String): Boolean = glyphName.removePrefix(PREFIX) in names

    /** Package words useful for search ("mozilla", "firefox"), without the generic ones ("com", "android", "app"). */
    fun packageWords(glyphName: String): List<String> =
        glyphName.removePrefix(PREFIX).split('_').filter { it.length > 1 && it !in genericWords }

    /** Name for an unlisted package: its most specific-looking word, capitalised (`com_example_notes` → "Example"). */
    fun guess(pkg: String): String {
        val words = pkg.split('_').filter { it.isNotEmpty() && it !in genericWords && it.length > 1 }
        val word = words.firstOrNull() ?: pkg.substringAfterLast('_')
        return word.replaceFirstChar { it.uppercaseChar() }
    }

    private val genericWords = setOf(
        "com", "org", "net", "io", "co", "uk", "de", "fr", "in", "jp", "tv", "me", "ml", "md", "ai", "cc", "ch", "cn",
        "br", "au", "eu", "pl", "ru", "tw", "us", "ee", "xyz", "android", "app", "apps", "application", "mobile",
        "client", "free", "pro", "lite", "the", "id",
    )

    private val names: Map<String, String> by lazy {
        TABLE.lineSequence().map { it.trim() }.filter { it.isNotEmpty() }.associate { line ->
            line.substringBefore('=') to line.substringAfter('=')
        }
    }

